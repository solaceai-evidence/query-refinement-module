def test_update_refinement_step_generated_examples_persists_list(test_db_session):
    """Saving quick-reply examples to a step can be read back from the DB."""
    step = _make_user_and_step(test_db_session)
    assert step.generated_examples is None

    examples = ["elderly patients (65+)", "working-age adults (18-64)", "children under 12"]
    updated = update_refinement_step_generated_examples(test_db_session, step.id, examples)

    assert updated is not None
    assert updated.generated_examples == examples

    refreshed = get_refinement_step(test_db_session, step.id)
    assert refreshed.generated_examples == examples


def test_update_refinement_step_generated_examples_can_overwrite(test_db_session):
    """A subsequent save replaces previous examples."""
    step = _make_user_and_step(test_db_session)

    update_refinement_step_generated_examples(test_db_session, step.id, ["option A", "option B"])
    update_refinement_step_generated_examples(test_db_session, step.id, ["new option X", "new option Y"])

    refreshed = get_refinement_step(test_db_session, step.id)
    assert refreshed.generated_examples == ["new option X", "new option Y"]


def test_update_refinement_step_generated_examples_empty_list(test_db_session):
    """An empty list is a valid value and overwrites previous non-empty data."""
    step = _make_user_and_step(test_db_session)
    update_refinement_step_generated_examples(test_db_session, step.id, ["a", "b"])
    update_refinement_step_generated_examples(test_db_session, step.id, [])

    refreshed = get_refinement_step(test_db_session, step.id)
    assert refreshed.generated_examples == []


def test_update_refinement_step_generated_examples_returns_none_for_missing_step(test_db_session):
    """Returns None gracefully when the step ID does not exist."""
    result = update_refinement_step_generated_examples(test_db_session, step_id=99999, examples=["x"])
    assert result is None


