def test_persist_generated_question_also_persists_examples():
    """When next_prompt includes examples, the examples CRUD is called too."""
    db_mock = MagicMock()
    db_steps = [SimpleNamespace(aspect_id="population", aspect_name="Population", id=7)]

    with patch(
        "query_refinement_module.api.routes.refinement.update_refinement_step_generated_question"
    ), patch(
        "query_refinement_module.api.routes.refinement.update_refinement_step_generated_examples"
    ) as mock_examples_crud:
        _persist_generated_question(
            db_mock,
            db_steps=db_steps,
            next_prompt={
                "aspect_id": "population",
                "name": "Population",
                "question": "Who are the patients?",
                "examples": ["elderly patients", "working-age adults", "children"],
            },
        )
        mock_examples_crud.assert_called_once_with(
            db_mock, 7, ["elderly patients", "working-age adults", "children"]
        )


